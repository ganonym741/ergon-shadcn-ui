const bool = (key: string, label: string, initial = false): Control => ({
  key,
  label,
  initial,
  type: 'boolean',
})
const text = (key: string, label: string, initial: string): Control => ({
  key,
  label,
  initial,
  type: 'text',
})
const area = (key: string, label: string, initial: string): Control => ({
  ...text(key, label, initial),
  type: 'textarea',
})
const num = (key: string, label: string, initial: number, min = 0, max = 100): Control => ({
  key,
  label,
  initial,
  type: 'number',
  min,
  max,
})
const select = (key: string, label: string, initial: string, options: string[]): Control => ({
  key,
  label,
  initial,
  options,
  type: 'select',
})
const json = (key: string, label: string, initial: unknown): Control => ({
  key,
  label,
  initial: JSON.stringify(initial, null, 2),
  type: 'json',
  jsonShape: Array.isArray(initial) ? 'array' : 'object',
})
const color = (key: string, label: string, initial: string): Control => ({
  ...text(key, label, initial),
  type: 'color',
})
