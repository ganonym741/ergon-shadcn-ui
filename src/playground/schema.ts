export interface PlaygroundSpec {
  id: string
  controls: Control[]
  presets: { name: string; values: Config }[]
}
export const playgrounds: Record<string, PlaygroundSpec> = Object.fromEntries(
  components.map((component) => {
    const fields = controls[component.id]
    if (!fields) throw new Error(`Missing playground controls: ${component.id}`)
    const defaults = Object.fromEntries(fields.map((field) => [field.key, field.initial]))
    return [
      component.id,
      {
        id: component.id,
        controls: fields,
        presets: [
          { name: 'Default', values: defaults },
          ...(component.id === 'rich-text-editor'
            ? [
                { name: 'Blank document', values: { ...defaults, initialHTML: '<p></p>' } },
                { name: 'Read only', values: { ...defaults, readOnly: true } },
                { name: 'Upload failure', values: { ...defaults, failure: true } },
                { name: 'Custom storage', values: { ...defaults, uploadMode: 'Custom endpoint' } },
              ]
            : []),
          ...(['table', 'table-plus'].includes(component.id)
            ? (['Nested rows', 'Row details', 'Nested table'] as const).map((rowMode) => ({
                name: rowMode,
                values: {
                  ...defaults,
                  rowMode,
                  rows: 4,
                  childCount: 2,
                  childLevels: 2,
                  expandFirst: true,
                  editing: true,
                  virtual: false,
                  ...(component.id === 'table'
                    ? { spans: false }
                    : { query: false, views: false, batch: false }),
                },
              }))
            : []),
          {
            name: 'Showcase',
            values: {
              ...defaults,
              ...Object.fromEntries(
                fields
                  .filter((field) => field.type === 'boolean')
                  .map((field) => [
                    field.key,
                    !['disabled', 'loading', 'error', 'failure', 'collapsed'].includes(field.key),
                  ]),
              ),
            },
          },
          { name: 'Compact', values: { ...defaults, _density: 'compact', _radius: 4 } },
          { name: 'Expressive', values: { ...defaults, _accent: '#6976c5', _radius: 16 } },
        ],
      },
    ]
  }),
)
export function defaultConfig(id: string): Config {
  return {
    ...playgrounds[id].presets[0].values,
    _density: 'comfortable',
    _direction: 'ltr',
    _radius: 10,
    _accent: '#b93e28',
  }
}
export function parseData<T>(config: Config, key: string, fallback: T): T {
  try {
    const parsed = JSON.parse(String(config[key]))
    return (Array.isArray(fallback) && !Array.isArray(parsed) ? fallback : parsed) as T
  } catch {
    return fallback
  }
}
