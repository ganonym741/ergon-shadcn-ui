import { components } from '@/catalog'
export type Config = Record<string, string | number | boolean>
export interface Control {
  key: string
  label: string
  type: 'text' | 'number' | 'boolean' | 'select' | 'color' | 'json'
  initial: string | number | boolean
  options?: string[]
  min?: number
  max?: number
  group?: string
}
const text = (key: string, label: string, initial = ''): Control => ({
  key,
  label,
  type: 'text',
  initial,
})
const num = (key: string, label: string, initial: number, min = 0, max = 100): Control => ({
  key,
  label,
  type: 'number',
  initial,
  min,
  max,
})
const bool = (key: string, label: string, initial = false): Control => ({
  key,
  label,
  type: 'boolean',
  initial,
})
const select = (key: string, label: string, initial: string, options: string[]): Control => ({
  key,
  label,
  type: 'select',
  initial,
  options,
})
const json = (key: string, label: string, initial: unknown): Control => ({
  key,
  label,
  type: 'json',
  initial: JSON.stringify(initial, null, 2),
  group: 'Data',
})
